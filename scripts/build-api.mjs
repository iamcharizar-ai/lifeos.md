// Bundles server/*.ts into api/*.js, the plain files Vercel runs as functions.
// Each one is self-contained (bridge/ is folded in), so nothing has to resolve a
// .ts import at run time. Run after any change to server/ or bridge/:
//   npm run api        (also part of `npm run build`)
import fs from 'node:fs'
import path from 'node:path'
import { rolldown } from 'rolldown'

const ROOT = path.resolve(import.meta.dirname, '..')
/**
 * source in server/ -> the routes it serves under /api. A source can serve several: the AI endpoints answer both at /api/ai
 * (secret in an Authorization header) and at /api/ai/<token> (the secret is the link you paste). `[token]` is Vercel's dynamic segment.
 */
const ROUTES = {
  'health-webhook': ['health-webhook'],
  'health-check': ['health-check'],
  'workout-push': ['workout-push'],
  ai: ['ai', 'ai/[token]'],
  mcp: ['mcp', 'mcp/[token]'],
}

fs.rmSync(path.join(ROOT, 'api'), { recursive: true, force: true })
let built = 0
for (const [src, routes] of Object.entries(ROUTES)) {
  const bundle = await rolldown({ input: path.join(ROOT, 'server', `${src}.ts`), platform: 'node', external: [/^node:/], logLevel: 'warn' })
  for (const route of routes) {
    const file = path.join(ROOT, 'api', `${route}.js`)
    await bundle.write({ file, format: 'esm', banner: `// GENERATED by scripts/build-api.mjs from server/${src}.ts. Do not edit by hand.` })
    built++
  }
  await bundle.close()
}
console.log(`built ${built} function(s) into api/`)
